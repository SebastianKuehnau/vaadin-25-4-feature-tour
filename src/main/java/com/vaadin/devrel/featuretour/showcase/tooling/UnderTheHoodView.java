package com.vaadin.devrel.featuretour.showcase.tooling;

import com.vaadin.devrel.featuretour.base.ui.GuideCards;
import com.vaadin.devrel.featuretour.base.ui.ShowcaseInfo;
import com.vaadin.devrel.featuretour.base.ui.ShowcasePage;
import com.vaadin.flow.component.html.Span;
import com.vaadin.flow.router.Menu;
import com.vaadin.flow.router.PageTitle;
import com.vaadin.flow.router.Route;
import com.vaadin.flow.server.Version;
import org.springframework.boot.SpringBootVersion;

@Route("under-the-hood")
@PageTitle("Under the Hood")
@Menu(title = "Under the Hood", parent = ToolingArea.class, order = 2)
@ShowcaseInfo(summary = "Hilla TypeScript in Java, leaner Spring dependencies, Node.js 26, Spring Boot 4.2, breaking changes.")
public class UnderTheHoodView extends ShowcasePage {

    public UnderTheHoodView() {
        super("Under the Hood",
                "Changes that need no demo but matter when you upgrade.",
                "https://vaadin.com/docs/v25/upgrading");

        var versions = new Span("This app runs Flow " + Version.getFullVersion() + " on Spring Boot "
                + SpringBootVersion.getVersion() + " and Java " + Runtime.version().feature() + ".");
        versions.addClassName("showcase-status");
        versions.setTestId("versions");
        add(versions);

        add(new GuideCards()
                .card("Spring Boot 4.2 and Node.js 26",
                        "Spring Boot 4.2 is the supported version of this minor. Node.js 26 is the minimum: if your "
                                + "global Node.js is older, Vaadin downloads Node.js 26 into ~/.vaadin. That's what "
                                + "happened when this app first built its dev bundle.")
                .card("Leaner vaadin-spring",
                        "vaadin-spring no longer brings Spring MVC, Spring WebSocket or Hibernate Validator. The Spring "
                                + "Boot starter adds the websocket and validation starters, so Boot apps like this one "
                                + "keep working. Plain Spring apps declare them themselves.")
                .card("Hilla: TypeScript generated in Java",
                        "Endpoint and model TypeScript is generated by Java in the same run that scans your classes, with "
                                + "no Node.js process. TypeScriptProcessor lets build tools run it. Removed: the generator "
                                + "plugin configuration, nodeCommand and hilla-openapi.json. Form models are now "
                                + "@vaadin/hilla-models constants.")
                .card("CDI and Quarkus on the Flow version",
                        "The CDI add-on and the Quarkus extension are developed in the Flow repository and versioned as "
                                + "25.4.x. Group and artifact IDs are unchanged.")
                .card("Observability Kit on lifecycle events",
                        "Navigation, request and session lock metrics are measured from Flow's new lifecycle events, and "
                                + "browser interaction timing works in production and with WebSocket push. See the "
                                + "Lifecycle Events page for the events themselves.")
                .card("Breaking changes",
                        "Check these when you upgrade:",
                        "The web component i18n property is undefined until you set it.",
                        "A slotted Card title now wins over cardTitle.",
                        "Date Picker calendar cells and Grid body cells have a new DOM: check custom CSS and tests.",
                        "Two-way signal bindings now require a write callback.",
                        "String-based event data and filters are deprecated (see Declared JavaScript)."));
    }
}
